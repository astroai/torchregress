# ---------------------------------------------------------------------------
# asymmetric Laplace NLL (kappa <-> tau pinball correspondence)
# ---------------------------------------------------------------------------


def asymmetric_laplace_nll_elementwise(y_pred: Tensor, target: Tensor, eps: float = 1e-6) -> Tensor:
    """Elementwise asymmetric-Laplace NLL.

    ``y_pred[..., 0]`` location mu, ``[..., 1]`` raw scale sigma
    (softplus-mapped), ``[..., 2]`` raw shape kappa (softplus-mapped, > 0).

    Density: ``f(y) = sqrt(2)*kappa/(sigma*(1+kappa^2)) *
    exp(-(sqrt(2)/(sigma*kappa))*max(y-mu, 0) - (sqrt(2)*kappa/sigma)*max(mu-y, 0))``.
    The negative log-likelihood equals its normalization constant plus
    ``(sqrt(2)*(1+kappa^2)/(sigma*kappa)) * rho_tau(y - mu)`` where
    ``rho_tau`` is the pinball/check loss at the quantile level
    ``tau = 1/(1 + kappa^2)`` — i.e. the kappa-tau correspondence.
    """
    _as_params(y_pred, 3, "asymmetric_laplace_nll")
    target = _align_target(target, y_pred)
    mu = y_pred[..., 0:1]
    sigma = _positive(y_pred[..., 1:2], eps)
    kappa = _positive(y_pred[..., 2:3], eps)
    u = target - mu
    above = u >= 0.0
    rate = torch.where(above, 1.0 / kappa, kappa) * (_SQRT2 / sigma)
    log_norm = math.log(_SQRT2) + torch.log(kappa) - torch.log(sigma) - torch.log1p(kappa * kappa)
    nll = -log_norm + rate * torch.abs(u)
    return nll.squeeze(-1)


@register_regression_loss("asymmetric_laplace_nll")
class AsymmetricLaplaceNLLLoss(BaseLoss):
    """Asymmetric-Laplace NLL; reduces to the scaled pinball NLL at
    ``tau = 1/(1 + kappa**2)``."""

    def __init__(
        self, eps: float = 1e-6, reduction: str = "mean", unconstrained_inputs: bool = True
    ) -> None:
        super().__init__(reduction=reduction)
        self.eps = eps
        self.unconstrained_inputs = unconstrained_inputs

    def forward(
        self,
        y_pred: Tensor,
        target: Tensor,
        mask: Optional[Tensor] = None,
        weights: Optional[Tensor] = None,
        **kw: object,
    ) -> Tensor:
        if not self.unconstrained_inputs:
            y_pred = y_pred.clone()
            y_pred[..., 1:2] = _inverse_softplus(y_pred[..., 1:2], self.eps)
            y_pred[..., 2:3] = _inverse_softplus(y_pred[..., 2:3], self.eps)
        return self._reduce(
            asymmetric_laplace_nll_elementwise(y_pred, target, eps=self.eps), mask, weights
        )


