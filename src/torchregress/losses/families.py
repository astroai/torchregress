"""Flexible-shape distributional losses (audit §6, item F5).

Each loss consumes the raw output matrix of a flexible-shape network head
(``y_pred[..., k]`` columns mapped to distribution parameters) and routes the
elementwise NLL through the unified ``BaseLoss._reduce`` pipeline
(mask = zero-fill, optional sample weights).

References:
- Azzalini (1985), "A class of distributions which includes the normal ones",
  Scand. J. Statist. 12, 171-178 (skew-normal).
- Azzalini & Capitanio (2003), "Distributions generated by perturbation of
  symmetry with emphasis on a multivariate skew t-distribution", JRSS-B 65,
  367-389 (skew-t).
- Ferrari & Cribari-Neto (2004), "Beta regression for modelling rates and
  proportions", J. Appl. Stat. 31, 799-815.
- Johnson, Kotz & Balakrishnan (1994), Continuous Univariate Distributions Vol. 1
  (Johnson SU; Shenton-Bowman moment quadrants for parameter interpretation).
- Jones & Pewsey (2009), "Sinh-arcsinh distributions", Biometrika 96, 761-780.
- Coles (2001), "An Introduction to Statistical Modeling of Extreme Values"
  (GEV parameterization).
- Koenker & Machado (1999), "Goodness of fit and related inference processes
  for quantile regression", JASA 94 (asymmetric Laplace / check-loss duality).
- Duan et al. (2020), "Adaptive Distributional Regression by Minimizing Sqr
  Loss" (SQR: sorted quantile levels trained with mean pinball loss).
"""

from __future__ import annotations

import math
from typing import Optional

import torch
import torch.nn.functional as F
from torch import Tensor

from .base import BaseLoss
from .loss_registry import register_regression_loss

_SQRT2 = math.sqrt(2.0)
_LOG_2PI = math.log(2.0 * math.pi)
_HALF_LOG_2PI = 0.5 * _LOG_2PI


# ---------------------------------------------------------------------------
# shared numerics
# ---------------------------------------------------------------------------


def _log_normal_cdf(x: Tensor) -> Tensor:
    """Log standard-normal CDF, exact in both tails.

    Delegates to :func:`torch.special.log_ndtr`, which uses an asymptotic
    expansion in the far lower tail. The previous ``log(clamp(Phi, tiny))``
    form saturated at ``log(float32 tiny) ~ -87`` (``x < ~-13``) in every
    dtype, zeroing the gradient of the skew-normal NLL w.r.t. alpha.
    """
    return torch.special.log_ndtr(x)


def _betacf(a: Tensor, b: Tensor, x: Tensor, itmax: int = 300, eps: float = 3e-14) -> Tensor:
    """Continued-fraction evaluation of the incomplete beta function
    (modified Lentz's method), vectorized over ``x``."""
    tiny = torch.finfo(x.dtype).tiny ** 0.5
    qab = a + b
    qap = a + 1.0
    qam = a - 1.0
    c = torch.ones_like(x)
    d = 1.0 - qab * x / qap
    d = torch.where(d.abs() < tiny, torch.full_like(d, tiny), d)
    d = 1.0 / d
    h = d
    for m in range(1, itmax + 1):
        m2 = 2 * m
        aa = m * (b - m) * x / ((qam + m2) * (a + m2))
        d = 1.0 + aa * d
        d = torch.where(d.abs() < tiny, torch.full_like(d, tiny), d)
        c = 1.0 + aa / c
        c = torch.where(c.abs() < tiny, torch.full_like(c, tiny), c)
        d = 1.0 / d
        h = h * d * c
        aa = -(a + m) * (qab + m) * x / ((a + m2) * (qap + m2))
        d = 1.0 + aa * d
        d = torch.where(d.abs() < tiny, torch.full_like(d, tiny), d)
        c = 1.0 + aa / c
        c = torch.where(c.abs() < tiny, torch.full_like(c, tiny), c)
        d = 1.0 / d
        delta = d * c
        h = h * delta
        if bool((delta - 1.0).abs().max() < eps):
            break
    return h


def _positive(raw: Tensor, eps: float) -> Tensor:
    return F.softplus(raw) + eps


def _inverse_softplus(sigma: Tensor, eps: float) -> Tensor:
    # ponytail: inverse of _positive for unconstrained_inputs=False mode.
    # softplus^{-1}(s) = log(expm1(s)) = s + log(-expm1(-s)); the second form
    # never overflows (expm1(s) is inf for s > ~88 in float32).
    s = (sigma - eps).clamp(min=1e-6)
    return s + torch.log(-torch.expm1(-s))


def _as_params(y_pred: Tensor, n_params: int, name: str) -> None:
    if y_pred.shape[-1] < n_params:
        raise ValueError(
            f"{name} expects at least {n_params} columns in the last dim of y_pred, "
            f"got {y_pred.shape[-1]}"
        )


def _align_target(target: Tensor, params: Tensor) -> Tensor:
    if target.dim() == params.dim() - 1:
        return target.unsqueeze(-1)
    return target


def _reduce_elementwise(
    elementwise: Tensor,
    reduction: str,
    mask: Optional[Tensor],
    weights: Optional[Tensor],
) -> Tensor:
    return BaseLoss(reduction=reduction)._reduce(elementwise, mask=mask, weights=weights)


# ---------------------------------------------------------------------------
# skew-normal NLL (Azzalini closed form)
# ---------------------------------------------------------------------------


def skew_normal_nll_elementwise(y_pred: Tensor, target: Tensor, eps: float = 1e-6) -> Tensor:
    """Elementwise skew-normal NLL.

    ``y_pred[..., 0]`` location xi, ``[..., 1]`` raw scale (softplus-mapped to
    omega > 0), ``[..., 2]`` skewness alpha. Density:
    ``f(y) = 2/omega * phi(z) * Phi(alpha z)``, ``z = (y - xi)/omega``.
    """
    target = _align_target(target, y_pred)
    xi = y_pred[..., 0:1]
    omega = _positive(y_pred[..., 1:2], eps)
    alpha = y_pred[..., 2:3]
    z = (target - xi) / omega
    log_pdf = (
        math.log(2.0) - _HALF_LOG_2PI - torch.log(omega) - 0.5 * z * z + _log_normal_cdf(alpha * z)
    )
    return -(log_pdf.squeeze(-1))


@register_regression_loss("skew_normal_nll")
class SkewNormalNLLLoss(BaseLoss):
    """Skew-normal NLL (Azzalini 1985). Reduces exactly to Gaussian NLL at alpha=0."""

    def __init__(
        self, eps: float = 1e-6, reduction: str = "mean", unconstrained_inputs: bool = True
    ) -> None:
        super().__init__(reduction=reduction)
        self.eps = eps
        self.unconstrained_inputs = unconstrained_inputs

    def forward(
        self,
        y_pred: Tensor,
        target: Tensor,
        mask: Optional[Tensor] = None,
        weights: Optional[Tensor] = None,
        **kw: object,
    ) -> Tensor:
        if not self.unconstrained_inputs:
            # y_pred[...,1] already positive sigma; map back through inverse softplus
            y_pred = y_pred.clone()
            y_pred[..., 1:2] = _inverse_softplus(y_pred[..., 1:2], self.eps)
        return self._reduce(
            skew_normal_nll_elementwise(y_pred, target, eps=self.eps), mask, weights
        )


def skew_normal_nll(
    y_pred: Tensor,
    target: Tensor,
    *,
    eps: float = 1e-6,
    reduction: str = "mean",
    mask: Optional[Tensor] = None,
    weights: Optional[Tensor] = None,
) -> Tensor:
    """Functional skew-normal NLL."""
    elementwise = skew_normal_nll_elementwise(y_pred, target, eps=eps)
    return _reduce_elementwise(elementwise, reduction, mask, weights)


# ---------------------------------------------------------------------------
# skew-t NLL (Azzalini-type, lgamma normalized)
# ---------------------------------------------------------------------------


def skew_t_nll_elementwise(y_pred: Tensor, target: Tensor, eps: float = 1e-6) -> Tensor:
    """Elementwise skew-t NLL.

    ``y_pred[..., 0]`` location xi, ``[..., 1]`` raw scale, ``[..., 2]``
    skewness alpha, ``[..., 3]`` raw dof nu (softplus-mapped). Density:
    ``f(y) = 2/omega * t_nu(z) * T_{nu+1}(alpha z sqrt((nu+1)/(nu+z^2)))``.
    """
    _as_params(y_pred, 4, "skew_t_nll")
    target = _align_target(target, y_pred)
    xi = y_pred[..., 0:1]
    omega = _positive(y_pred[..., 1:2], eps)
    alpha = y_pred[..., 2:3]
    nu = _positive(y_pred[..., 3:4], eps)
    z = (target - xi) / omega
    log_t_pdf = (
        torch.lgamma((nu + 1.0) / 2.0)
        - torch.lgamma(nu / 2.0)
        - 0.5 * torch.log(nu * math.pi)
        - torch.log(omega)
        - ((nu + 1.0) / 2.0) * torch.log1p(z * z / nu)
    )
    w = alpha * z * torch.sqrt((nu + 1.0) / (nu + z * z))
    log_cdf_term = _student_t_log_cdf_vec(w, nu + 1.0)
    return -(math.log(2.0) + log_t_pdf + log_cdf_term).squeeze(-1)


def _student_t_log_cdf_vec(x: Tensor, df: Tensor) -> Tensor:
    """Log CDF of Student-t with elementwise dof ``df`` (tensor-valued).

    Two continued-fraction branches of the regularised incomplete beta, each
    used where it converges (Numerical Recipes ``betai`` switch), computed in
    float64 and returned in the dtype of ``x``:

    * centre, ``u = x^2 / (df + x^2) < 1.5 / (df/2 + 2.5)``:
      ``T(x) = 1/2 + 1/2 sign(x) I_u(1/2, df/2)``. The prefactor
      ``sign(x) u^{1/2} = x / sqrt(df + x^2)`` is written without ``|x|`` or
      ``log u``, so the value and its gradient are smooth through ``x = 0``
      (``dT/dx = t_df(0)`` there).
    * tails: ``T(x) = 1/2 I_{df/(df+x^2)}(df/2, 1/2)`` for ``x < 0`` (and
      ``1 -`` that for ``x > 0``), evaluated in log space.

    The previous single-branch form evaluated ``I_{df/(df+x^2)}(df/2, 1/2)``
    with the argument clamped at ``1 - 1e-15``; ``d/dx [df/(df+x^2)] = 0`` at
    ``x = 0`` and the clamp has a zero gradient, so ``d log T / dx`` was
    exactly 0 at ``x = 0`` (the skew-t never learned ``alpha`` from 0).
    """
    dtype = x.dtype
    f64 = torch.float64
    x64 = x.to(f64)
    df64 = df.to(f64)
    x2 = x64 * x64
    denom = df64 + x2
    u = x2 / denom  # 1 - xb, exact for small |x|
    xb = df64 / denom
    half_df = 0.5 * df64
    central = u < 1.5 / (half_df + 2.5)
    # One continued-fraction call for both branches: I_u(1/2, df/2) in the
    # centre, I_xb(df/2, 1/2) in the tails. Unused-branch inputs are replaced
    # by safe values so no inf/NaN reaches the backward pass through where().
    aa = torch.where(central, torch.full_like(df64, 0.5), half_df)
    bb = torch.where(central, half_df, torch.full_like(df64, 0.5))
    cf = _betacf(aa, bb, torch.where(central, u, xb))
    ln_norm = torch.lgamma(aa + bb) - torch.lgamma(aa) - torch.lgamma(bb) - torch.log(aa)

    # centre: s = sign(x) I_u(1/2, df/2) = x / sqrt(df + x^2) * xb^{df/2} * norm * cf
    x_c = torch.where(central, x64, torch.zeros_like(x64))
    denom_c = torch.where(central, denom, torch.ones_like(denom))
    xb_c = torch.where(central, xb, torch.ones_like(xb))
    s = x_c / torch.sqrt(denom_c) * torch.exp(ln_norm + bb * torch.log(xb_c)) * cf
    log_central = math.log(0.5) + torch.log1p(s)

    # tails: log(1/2 I_xb(df/2, 1/2)) = log 1/2 + norm + df/2 log xb + 1/2 log u + log cf
    tiny = torch.finfo(f64).tiny
    xb_t = torch.where(central, torch.full_like(xb, 0.5), xb).clamp_min(tiny)
    u_t = torch.where(central, torch.full_like(u, 0.5), u)
    cf_t = torch.where(central, torch.ones_like(cf), cf).clamp_min(tiny)
    half_log = (
        math.log(0.5) + ln_norm + aa * torch.log(xb_t) + bb * torch.log(u_t) + torch.log(cf_t)
    )
    upper = torch.log1p(-torch.exp(torch.where(x64 > 0.0, half_log, torch.full_like(x64, -1.0))))
    log_tail = torch.where(x64 > 0.0, upper, half_log)
    return torch.where(central, log_central, log_tail).to(dtype)


def _reg_inc_beta(a: Tensor, b: Tensor, x: Tensor) -> Tensor:
    """Regularized incomplete beta I_x(a, b), elementwise, with the standard
    symmetry branch ``I_x(a, b) = 1 - I_{1-x}(b, a)`` for large x (the
    continued fraction only converges well away from x = 1).

    Computed internally in float64: at fp32 the ``log1p(-x)``/``lgamma``
    backward passes overflow to inf for boundary inputs (x→1, large a/b),
    NaN-ing any net in a few steps (found via skew-t harness smoke).
    The output is a probability — clamped to [0, 1] on return.
    """
    dtype = x.dtype
    device = x.device
    a64 = a.to(torch.float64)
    b64 = b.to(torch.float64)
    x64 = x.to(torch.float64).clamp(torch.finfo(torch.float64).tiny, 1.0 - 1e-15)
    ln_bt = (
        torch.lgamma(a64 + b64)
        - torch.lgamma(a64)
        - torch.lgamma(b64)
        + a64 * torch.log(x64)
        + b64 * torch.log1p(-x64)
    )
    bt = torch.exp(ln_bt)
    sym = x64 > (a64 + 1.0) / (a64 + b64 + 2.0)
    xs = torch.where(sym, 1.0 - x64, x64)
    aa = torch.where(sym, b64, a64)
    bb = torch.where(sym, a64, b64)
    cf = _betacf(aa, bb, xs)
    # Numerical Recipes ``betai``: I_x(a, b) = bt * cf(a, b, x) / a, and under
    # symmetry 1 - bt * cf(b, a, 1 - x) / b. ``aa`` already holds b on the
    # symmetric branch, so both branches divide by ``aa``.
    out = torch.where(sym, 1.0 - bt * cf / aa, bt * cf / aa)
    return out.clamp(0.0, 1.0).to(device=device, dtype=dtype)


