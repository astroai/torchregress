# ---------------------------------------------------------------------------
# SQR loss (sorted quantile levels, mean pinball)
# ---------------------------------------------------------------------------


def sqr_loss_elementwise(y_pred: Tensor, target: Tensor, n_levels: Optional[int] = None) -> Tensor:
    """Elementwise SQR loss (Duan et al. 2020).

    ``y_pred[..., j]`` are the L=``n_levels`` quantile-level predictions; they
    are made monotone with a running maximum (:func:`torch.cummax`) so the
    predicted quantile curve is sorted by construction. The loss is the mean
    pinball across levels ``tau_j = j/(L+1)``.
    """
    if y_pred.dim() < 2:
        raise ValueError(
            f"sqr_loss expects [batch, levels] predictions, got shape {tuple(y_pred.shape)}"
        )
    levels = y_pred.shape[1]
    if n_levels is not None and levels != n_levels:
        raise ValueError(f"sqr_loss expected {n_levels} levels, got {levels}")
    sorted_q = torch.cummax(y_pred, dim=1).values
    tau = torch.arange(1, levels + 1, device=y_pred.device, dtype=y_pred.dtype) / (levels + 1.0)
    if target.dim() == y_pred.dim() - 1:
        target = target.unsqueeze(-1)
    elif target.dim() != y_pred.dim() or target.shape[-1] != 1:
        # A [B, 1] target broadcasts against [B, L]; anything else (e.g. the
        # old ``target.unsqueeze(-1)`` of a [B, 1] target) would silently pair
        # every sample with every other sample.
        raise ValueError(
            f"sqr_loss expects targets of shape {tuple(y_pred.shape[:-1])} or "
            f"{tuple(y_pred.shape[:-1]) + (1,)}, got {tuple(target.shape)}"
        )
    diff = target - sorted_q
    pinball = torch.maximum(tau * diff, (tau - 1.0) * diff)
    return pinball.mean(dim=-1)


@register_regression_loss("sqr_loss")
class SQRLoss(BaseLoss):
    """Distributional quantile regression via sorted levels + mean pinball
    (Duan et al., 2020). The head outputs L quantile levels; monotonicity is
    enforced with a cumulative max."""

    def __init__(self, n_levels: int = 32, reduction: str = "mean") -> None:
        super().__init__(reduction=reduction)
        self.n_levels = n_levels

    def forward(
        self,
        y_pred: Tensor,
        target: Tensor,
        mask: Optional[Tensor] = None,
        weights: Optional[Tensor] = None,
        **kw: object,
    ) -> Tensor:
        return self._reduce(
            sqr_loss_elementwise(y_pred, target, n_levels=self.n_levels), mask, weights
        )


def sqr_loss(
    y_pred: Tensor,
    target: Tensor,
    *,
    n_levels: int = 32,
    reduction: str = "mean",
    mask: Optional[Tensor] = None,
    weights: Optional[Tensor] = None,
) -> Tensor:
    """Functional SQR loss over ``n_levels`` sorted quantile levels."""
    elementwise = sqr_loss_elementwise(y_pred, target, n_levels=n_levels)
    return _reduce_elementwise(elementwise, reduction, mask, weights)


