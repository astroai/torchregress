# ---------------------------------------------------------------------------
# sinh-arcsinh NLL (Jones & Pewsey)
# ---------------------------------------------------------------------------


def sinh_arcsinh_nll_elementwise(y_pred: Tensor, target: Tensor, eps: float = 1e-6) -> Tensor:
    """Elementwise sinh-arcsinh NLL.

    ``y_pred[..., 0]`` location mu, ``[..., 1]`` raw scale sigma,
    ``[..., 2]`` skewness epsilon, ``[..., 3]`` raw tail-weight delta
    (softplus-mapped). With ``z = (y - mu)/sigma`` and
    ``s = sinh((asinh(z) - epsilon)/delta)`` (the inverse of the Jones &
    Pewsey transformation ``x = mu + sigma*sinh(delta*asinh(Z) + epsilon)``
    for standard-normal Z), the NLL is
    ``0.5*log(2 pi) + log(sigma*delta) + 0.5*log1p(z^2)
    - 0.5*log1p(s^2) + s^2/2``.
    At epsilon=0, delta=1 this reduces exactly to the Gaussian NLL.
    """
    _as_params(y_pred, 4, "sinh_arcsinh_nll")
    target = _align_target(target, y_pred)
    mu = y_pred[..., 0:1]
    sigma = _positive(y_pred[..., 1:2], eps)
    skew_eps = y_pred[..., 2:3]
    delta = _positive(y_pred[..., 3:4], eps)
    z = (target - mu) / sigma
    w = (torch.asinh(z) - skew_eps) / delta
    s = torch.sinh(w)
    nll = (
        _HALF_LOG_2PI
        + torch.log(sigma)
        + torch.log(delta)
        + 0.5 * torch.log1p(z * z)
        - 0.5 * torch.log1p(s * s)
        + 0.5 * s * s
    )
    return nll.squeeze(-1)


