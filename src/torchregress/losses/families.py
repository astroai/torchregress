def johnson_su_nll_elementwise(y_pred: Tensor, target: Tensor, eps: float = 1e-6) -> Tensor:
    """Elementwise Johnson-SU NLL.

    ``y_pred[..., 0]`` location xi, ``[..., 1]`` raw scale lambda
    (softplus-mapped), ``[..., 2]`` shape gamma, ``[..., 3]`` raw shape delta
    (softplus-mapped). Standardized variate: ``Z = gamma + delta*asinh(u)``,
    ``u = (y - xi)/lambda`` (Shenton-quadrant moment interpretation applies to
    (gamma, delta)).
    """
    _as_params(y_pred, 4, "johnson_su_nll")
    target = _align_target(target, y_pred)
    xi = y_pred[..., 0:1]
    lam = _positive(y_pred[..., 1:2], eps)
    gamma = y_pred[..., 2:3]
    delta = _positive(y_pred[..., 3:4], eps)
    u = (target - xi) / lam
    z = gamma + delta * torch.asinh(u)
    nll = _HALF_LOG_2PI - torch.log(delta) + torch.log(lam) + 0.5 * torch.log1p(u * u) + 0.5 * z * z
    return nll.squeeze(-1)


