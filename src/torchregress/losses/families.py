# ---------------------------------------------------------------------------
# GEV NLL (xi -> 0 Gumbel limit analytic)
# ---------------------------------------------------------------------------

_GUMBEL_XI_THRESHOLD = 1e-6


def gev_nll_elementwise(y_pred: Tensor, target: Tensor, eps: float = 1e-6) -> Tensor:
    """Elementwise generalized-extreme-value NLL (Coles parameterization).

    ``y_pred[..., 0]`` location mu, ``[..., 1]`` raw scale sigma
    (softplus-mapped), ``[..., 2]`` shape xi. For |xi| below
    ``_GUMBEL_XI_THRESHOLD`` the analytic Gumbel limit is used. Observations
    outside the support ``1 + xi*z > 0`` receive infinite NLL.
    """
    _as_params(y_pred, 3, "gev_nll")
    target = _align_target(target, y_pred)
    mu = y_pred[..., 0:1]
    sigma = _positive(y_pred[..., 1:2], eps)
    xi = y_pred[..., 2:3]
    z = (target - mu) / sigma
    gumbel = torch.log(sigma) + z + torch.exp(-z)
    use_gumbel = xi.abs() < _GUMBEL_XI_THRESHOLD
    # ponytail: compute gev branch only where needed; torch.where does not short-circuit
    # so 1/xi and pow(-1/xi) must not be evaluated for |xi|<threshold or unsupported t.
    t = 1.0 + xi * z
    supported = t > 0.0
    # ponytail: torch.where doesn't short-circuit; mask both pow and log to keep finite graph.
    # Use 1.0 for t and threshold for xi where branch not taken.
    use_gev = (~use_gumbel) & supported
    xi_safe = torch.where(use_gev, xi, torch.full_like(xi, _GUMBEL_XI_THRESHOLD))
    t_safe = torch.where(use_gev, t, torch.full_like(t, 1.0))
    gev_raw = (
        torch.log(sigma) + (1.0 + 1.0 / xi_safe) * torch.log(t_safe) + t_safe.pow(-1.0 / xi_safe)
    )
    gev = torch.where(supported, gev_raw, torch.full_like(gev_raw, float("inf")))
    return torch.where(use_gumbel, gumbel, gev).squeeze(-1)


@register_regression_loss("gev_nll")
class GEVNLLLoss(BaseLoss):
    """GEV NLL with an analytic Gumbel limit as xi -> 0."""

    def __init__(self, eps: float = 1e-6, reduction: str = "mean") -> None:
        super().__init__(reduction=reduction)
        self.eps = eps

    def forward(
        self,
        y_pred: Tensor,
        target: Tensor,
        mask: Optional[Tensor] = None,
        weights: Optional[Tensor] = None,
        **kw: object,
    ) -> Tensor:
        return self._reduce(gev_nll_elementwise(y_pred, target, eps=self.eps), mask, weights)


